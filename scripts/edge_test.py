#!/usr/bin/env python3
import subprocess, sys
tests = [
    ('1', '1'),
    ('9', '9'),
    ('9999', '9999'),
    ('10000', '10000'),
    ('12345', '12345'),
    ('12345678', '12345678'),
    ('123456789', '123456789'),
    ('1234567890123456', '1234567890123456'),
    ('12345678901234567', '12345678901234567'),
    ('1234567890123456789012345', '1234567890123456789012345'),
    ('9999999999999999', '9999999999999999'),
    ('10000000000000000', '10000000000000000'),
    ('99999999999999999999999999999999', '99999999999999999999999999999999'),
    ('-1234567890123456789', '-1234567890123456789'),
    ('-12345678901234567', '-12345678901234567'),
    ('-9999', '-9999'),
    ('-1', '-1'),
    ('0', '0'),
]
fails = 0
for a, b in tests:
    inp = '1\n' + a + '\n' + b + '\n'
    r = subprocess.run(['./mf_ADD'], input=inp.encode(), capture_output=True)
    out = r.stdout.decode().strip()
    exp = str(int(a) + int(b))
    ok = 'OK' if out == exp else 'FAIL'
    if ok == 'FAIL':
        fails += 1
        print(f'{ok}: {a} + {b} = {out} (exp {exp})')
    else:
        print(f'{ok}: {a[:25]} + {b[:25]} = {out[:25]}...')
print(f'\nTotal fails: {fails}/{len(tests)}')
sys.exit(1 if fails else 0)
